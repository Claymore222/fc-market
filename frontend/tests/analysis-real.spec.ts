import { test, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

test('phase A works with the isolated copied career and persists only application preferences', async ({ page }) => {
  const base = process.env.FC_ANALYSIS_REAL_URL, uid = process.env.FC_ANALYSIS_REAL_UID
  test.skip(!base || !uid, 'Requires a copied career database and a separate scratch app.db.')
  const out = resolve('..', 'scratch', 'analysis-phase-a')
  await mkdir(out, { recursive: true })
  const started = Date.now()
  const response = await page.request.get(`${base}/api/analysis/profile?saveUid=${uid}`)
  expect(response.ok()).toBeTruthy()
  const data = await response.json()
  const ms = Date.now() - started
  expect(data.context.viewMode).toBe('saved')
  expect(data.context.players.length).toBeGreaterThan(10)
  expect(data.context.coverage.find((c: {key: string}) => c.key === 'attributes').known).toBeGreaterThan(0)
  await page.addInitScript(uid => localStorage.setItem('fcm.save', uid), uid!)
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${base}/transfer/plan`)
  await expect(page.getByTestId('analysis-source')).toContainText('Kayıtlı kariyer planı')
  await page.getByLabel('Ana diziliş', { exact: true }).selectOption('4-3-3')
  await page.getByLabel('Ayırdığın bonservis bütçesi', { exact: true }).fill('10000000')
  await page.getByLabel('Ayırdığın maaş bütçesi', { exact: true }).fill('50000')
  await page.getByLabel('Takım projesi', { exact: true }).selectOption('develop')
  await page.getByRole('button', { name: 'Planı kaydet', exact: true }).click()
  await expect(page.getByText('Plan kaydedildi.', { exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: resolve(out, 'profile-desktop.png'), fullPage: true, animations: 'disabled' })
  await page.reload()
  await expect(page.getByLabel('Ana diziliş', { exact: true })).toHaveValue('4-3-3')
  await expect(page.getByLabel('Ayırdığın bonservis bütçesi', { exact: true })).toHaveValue('10000000')
  await expect(page.getByLabel('Takım projesi', { exact: true })).toHaveValue('develop')
  await page.getByRole('button', { name: 'Export’u incele' }).click()
  await expect(page.getByTestId('analysis-source')).toContainText('Ayrı export önizleme planı')
  await expect(page.getByLabel('Ayırdığın bonservis bütçesi', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Kaydedilmiş kayda dön' }).click()
  await expect(page.getByLabel('Ayırdığın bonservis bütçesi', { exact: true })).toHaveValue('10000000')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  expect(await page.locator('.analysis-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: resolve(out, 'profile-mobile.png'), fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
  await writeFile(resolve(out, 'real-check.json'), JSON.stringify({ requestMs: ms, snapshot: data.context.snapshot, scope: data.context.scopeKey, coverage: data.context.coverage, players: data.context.players.length, errors }, null, 2))
})
