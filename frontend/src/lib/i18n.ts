export type MessageKey = keyof typeof tr

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = tr[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}
